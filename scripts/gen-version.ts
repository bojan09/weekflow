import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseChangelog } from "../src/lib/changelog";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const pkg = JSON.parse(readFileSync(resolve(root, "package.json"), "utf8")) as {
  version: string;
};
const releases = parseChangelog(readFileSync(resolve(root, "CHANGELOG.md"), "utf8"));

const latest = releases[0];
if (!latest) throw new Error("CHANGELOG.md has no releases");
if (latest.version !== pkg.version) {
  console.error(
    `Version mismatch: package.json is ${pkg.version} but the newest CHANGELOG.md entry is ${latest.version}.`,
  );
  process.exit(1);
}

const buildDate = process.env.WEEKFLOW_BUILD_DATE ?? new Date().toISOString().slice(0, 10);

const out = resolve(root, "src/generated/version.ts");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// GENERATED by scripts/gen-version.ts — do not edit.
import type { Release } from "@/lib/changelog";

export const APP_VERSION = ${JSON.stringify(pkg.version)};
export const BUILD_DATE = ${JSON.stringify(buildDate)};
export const RELEASES: readonly Release[] = ${JSON.stringify(releases, null, 2)};
`,
);
console.log(`gen-version: ${pkg.version} (build ${buildDate}), ${releases.length} release(s)`);
